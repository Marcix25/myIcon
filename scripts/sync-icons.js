//= SYNC ICONS
// reads the plain .svg files in svg/ and writes them into scss/_glyphs.scss as the
// url("data:image/svg+xml,...") data URIs the stylesheet consumes, plus the two maps that list them.
// Run it after adding or editing a file in svg/ (npm run build runs it for you):
// npm run sync
//
// This folder is the one place the original .svg files live. mypgs keeps no .svg of its own: its
// scripts/sync-icons.js reads the few glyphs the library draws by itself from here.
//
// Naming convention read from svg/:
// - "icon-name.svg" is a single-layer glyph -> $icon-name, added to $icons-builtin under the bare
//   key "name", which scss/index.scss turns into the icon bracket flag icon-name and the
//   --icon-glyph-name custom property.
// - "icon-name-before.svg" + "icon-name-after.svg" (same base name, -before/-after suffix) are the
//   two layers of a duo glyph -> $icon-name-before/-after, paired as name in $icons-duo. -before
//   draws on ::before, -after on ::after. The duo needs the flat "icon-name.svg" too.
//
// scss/_glyphs.scss is rewritten whole on every run. What is edited by hand is scss/index.scss.
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SVG_DIR = path.join(ROOT, "svg");
const GLYPHS_SCSS = path.join(ROOT, "scss/_glyphs.scss");

function encodeSvg(raw) {
    return raw
        .replace(/<\?xml[^>]*\?>/g, "")
        .trim()
        .replace(/\r?\n\s*/g, " ")
        .replace(/"/g, "'")
        .replace(/</g, "%3C")
        .replace(/>/g, "%3E")
        .replace(/#/g, "%23")
        .replace(/\s+/g, " ")
        .trim();
}

function readIcons() {
    const files = fs.readdirSync(SVG_DIR).filter(f => f.endsWith(".svg")).sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }));
    const before = new Map();
    const after = new Map();
    const singles = new Map();

    files.forEach(file => {
        const base = file.slice(0, -4);
        if (!base.startsWith("icon-")) {
            console.warn(`[sync-icons] "${file}" does not start with "icon-", skipped`);
            return;
        }
        const raw = fs.readFileSync(path.join(SVG_DIR, file), "utf8");
        if (base.endsWith("-before")) before.set(base.slice("icon-".length, -"-before".length), raw);
        else if (base.endsWith("-after")) after.set(base.slice("icon-".length, -"-after".length), raw);
        else singles.set(base.slice("icon-".length), raw);
    });

    const duos = new Map();
    before.forEach((raw, name) => {
        if (!after.has(name)) return console.warn(`[sync-icons] "icon-${name}-before.svg" has no matching "-after.svg", skipped`);
        if (!singles.has(name)) console.warn(`[sync-icons] "icon-${name}-before/-after.svg" has no flat "icon-${name}.svg": iconDuo draws it, but the plain glyph does not exist`);
        duos.set(name, { before: raw, after: after.get(name) });
    });
    after.forEach((_, name) => {
        if (!before.has(name)) console.warn(`[sync-icons] "icon-${name}-after.svg" has no matching "-before.svg", skipped`);
    });

    return { singles, duos };
}

function declaration(varName, raw) {
    return `$${varName}: url("data:image/svg+xml,${encodeSvg(raw)}");`;
}

function main() {
    const { singles, duos } = readIcons();
    const lines = [
        "//= GLYPHS",
        "// Generated by `npm run sync` (scripts/sync-icons.js) from the .svg files in svg/. Edit or add an icon",
        "// there and re-run it, rather than hand-editing the data URIs below; the stylesheet itself is",
        "// scss/index.scss.",
        "",
        "//# DRAWINGS",
    ];
    singles.forEach((raw, name) => lines.push(declaration(`icon-${name}`, raw)));
    duos.forEach(({ before, after }, name) => {
        lines.push(declaration(`icon-${name}-before`, before), declaration(`icon-${name}-after`, after));
    });

    lines.push(
        "",
        "//# THE DRAWABLE SET",
        "// The key is the bare glyph name: the two prefixes are written where they are used, icon- for the",
        "// public option (pgs \"icon['icon-star']\") and --icon-glyph- for the custom property that carries the",
        "// drawing, so the glyphs never mix with the icon's own configuration. Removing or renaming a key is",
        "// a breaking change, since the keys are public through that option.",
        "$icons-builtin: ("
    );
    singles.forEach((_, name) => lines.push(`    ${name}: $icon-${name},`));
    lines.push(
        ");",
        "",
        "//# TWO-LAYER GLYPHS",
        "// Unlike the single-path set above, their paths are drawn on ::before and ::after so a component can",
        "// color or animate each layer independently.",
        "$icons-duo: ("
    );
    duos.forEach((_, name) => lines.push(`    ${name}: ($icon-${name}-before, $icon-${name}-after),`));
    lines.push(");", "");

    fs.mkdirSync(path.dirname(GLYPHS_SCSS), { recursive: true });
    fs.writeFileSync(GLYPHS_SCSS, lines.join("\n"), "utf8");
    console.log(`[sync-icons] ${singles.size} glyphs, ${duos.size} duo, written to scss/_glyphs.scss.`);
}

main();
